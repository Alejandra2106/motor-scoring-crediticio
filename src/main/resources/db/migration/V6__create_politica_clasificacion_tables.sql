CREATE TABLE politica_clasificacion (
    id_politica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_publicacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_politica_clasificacion_version
        UNIQUE (version),
    CONSTRAINT ck_politica_clasificacion_version
        CHECK (version > 0),
    CONSTRAINT ck_politica_clasificacion_fechas_iguales
        CHECK (fecha_creacion = fecha_publicacion)
);

CREATE TABLE rango_clasificacion (
    id_rango BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_politica BIGINT NOT NULL,
    categoria VARCHAR(10) NOT NULL,
    limite_inferior INTEGER NOT NULL,
    limite_superior INTEGER NOT NULL,
    CONSTRAINT fk_rango_clasificacion_politica
        FOREIGN KEY (id_politica)
        REFERENCES politica_clasificacion (id_politica),
    CONSTRAINT uq_rango_clasificacion_politica_categoria
        UNIQUE (id_politica, categoria),
    CONSTRAINT ck_rango_clasificacion_categoria
        CHECK (categoria IN ('BAJO', 'MEDIO', 'ALTO')),
    CONSTRAINT ck_rango_clasificacion_limite_inferior
        CHECK (limite_inferior >= -100),
    CONSTRAINT ck_rango_clasificacion_limite_superior
        CHECK (limite_superior <= 130),
    CONSTRAINT ck_rango_clasificacion_limites
        CHECK (limite_inferior <= limite_superior)
);

CREATE TABLE configuracion_clasificacion_actual (
    id_configuracion SMALLINT NOT NULL DEFAULT 1 PRIMARY KEY,
    id_politica BIGINT NULL,
    CONSTRAINT fk_configuracion_clasificacion_actual_politica
        FOREIGN KEY (id_politica)
        REFERENCES politica_clasificacion (id_politica),
    CONSTRAINT ck_configuracion_clasificacion_actual_id
        CHECK (id_configuracion = 1)
);

