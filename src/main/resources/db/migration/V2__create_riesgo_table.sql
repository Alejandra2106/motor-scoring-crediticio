CREATE TABLE riesgo (
    id_riesgo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable VARCHAR(30) NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVA',
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_riesgo_variable UNIQUE (variable),
    CONSTRAINT ck_riesgo_variable CHECK (variable IN ('INGRESOS_MENSUALES', 'NIVEL_ENDEUDAMIENTO', 'NUMERO_MORAS', 'HISTORIAL_CREDITICIO', 'ANTIGUEDAD_LABORAL')),
    CONSTRAINT ck_riesgo_estado CHECK (estado = 'ACTIVA')
);
